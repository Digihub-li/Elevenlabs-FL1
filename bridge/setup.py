def rtp(env: dict[str, str]) -> str:
    return f"""[general]
rtpstart=10000
rtpend=10100
externaddr={env["PUBLIC_IP"]}
localnet={env.get("LOCAL_NET", "10.0.0.0/8")}
; Lock RTP to the first source seen for a stream (blocks injected audio).
strictrtp=yes
; Packets in sequence needed before a new source is accepted (Asterisk default).
probation=4
"""


def main() -> None:
    env = load_env(ENV_PATH)
    require(env)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "pjsip.conf").write_text(pjsip(env))
    (OUT / "extensions.conf").write_text(extensions(env))
    (OUT / "rtp.conf").write_text(rtp(env))
    print(f"Wrote config in {OUT} (contents not printed).")


if __name__ == "__main__":
    main()
