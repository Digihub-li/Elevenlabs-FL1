#!/usr/bin/env python3
"""Render Asterisk config from ../.env. Does not print secrets."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = ROOT / ".env"
OUT = Path(__file__).resolve().parent / "asterisk"

REQUIRED = (
    "PUBLIC_IP",
    "BIND_IP",
    "FL1_SIP_USER",
    "FL1_SIP_PASSWORD",
    "FL1_SIP_DOMAIN",
    "DID",
)


def load_env(path: Path) -> dict[str, str]:
    if not path.exists():
        sys.exit(f"Missing {path}. Copy .env.example to .env first.")
    env: dict[str, str] = {}
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if (value.startswith('"') and value.endswith('"')) or (
            value.startswith("'") and value.endswith("'")
        ):
            value = value[1:-1]
        env[key.strip()] = value
    return env


def require(env: dict[str, str]) -> None:
    missing = [key for key in REQUIRED if not env.get(key)]
    placeholders = []
    if env.get("FL1_SIP_PASSWORD") in {"", "change-me"}:
        placeholders.append("FL1_SIP_PASSWORD")
    if env.get("FL1_SIP_USER") in {"", "your-trunk-username"}:
        placeholders.append("FL1_SIP_USER")
    if env.get("PUBLIC_IP") in {"", "203.0.113.10"}:
        placeholders.append("PUBLIC_IP")
    if missing or placeholders:
        bits = []
        if missing:
            bits.append("missing: " + ", ".join(missing))
        if placeholders:
            bits.append("still placeholder: " + ", ".join(placeholders))
        sys.exit("Fill .env before setup. " + " ".join(bits))


