#!/usr/bin/env python3
"""Render Asterisk config from ../.env. Does not print secrets."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = ROOT / ".env"
