def extensions(env: dict[str, str]) -> str:
    host = env.get("FL1_SIP_HOST", "sbc6.ipbx.li")
    port = env.get("FL1_SIP_PORT", "5083")
    did = env["DID"].lstrip("+")
    cli = env.get("CLI_NAME", "Bridge")
    return f"""; Generated by bridge/setup.py

[general]
static=yes
writeprotect=no
clearglobalvars=no

[from-trunk]
exten => _X.,1,NoOp(Inbound from trunk ${{CALLERID(all)}} -> ElevenLabs)
 same => n,Dial(PJSIP/elevenlabs,120)
 same => n,Hangup()

exten => {did},1,Goto(from-trunk,${{EXTEN}},1)

[outbound]
exten => _+X.,1,NoOp(Outbound PSTN ${{EXTEN}})
 same => n,Set(NUM=${{EXTEN:1}})
 same => n,Set(CALLERID(all)="{cli}" <+{did}>)
 same => n,Dial(PJSIP/fl1-outbound/sip:${{NUM}}@{host}:{port}\\;transport=tcp,90)
 same => n,Hangup()

exten => _X.,1,NoOp(Outbound PSTN ${{EXTEN}})
 same => n,Set(CALLERID(all)="{cli}" <+{did}>)
 same => n,Dial(PJSIP/fl1-outbound/sip:${{EXTEN}}@{host}:{port}\\;transport=tcp,90)
 same => n,Hangup()

[from-elevenlabs]
exten => _+X.,1,Goto(outbound,${{EXTEN}},1)
exten => _X.,1,Goto(outbound,${{EXTEN}},1)

[from-trunk-outbound]
exten => _X.,1,Hangup()
"""


def rtp(env: dict[str, str]) -> str:
    return f"""[general]
rtpstart=10000
rtpend=10100
externaddr={env["PUBLIC_IP"]}
localnet={env.get("LOCAL_NET", "10.0.0.0/8")}
strictrtp=no
probation=0
"""


def main() -> None:
    env = load_env(ENV_PATH)
    require(env)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "pjsip.conf").write_text(pjsip(env))
    (OUT / "extensions.conf").write_text(extensions(env))
    (OUT / "rtp.conf").write_text(rtp(env))
    print(f"Wrote config in {OUT} (contents not printed).")


if __name__ == "__main__":
    main()
